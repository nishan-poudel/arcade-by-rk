<script setup lang="ts">
import { type HTMLAttributes, computed } from 'vue'
import { SwitchRoot, SwitchThumb } from 'reka-ui'
import { cn } from '@/lib/utils'

const props = defineProps<{
  modelValue?: boolean
  class?: HTMLAttributes['class']
}>()
const emit = defineEmits<{ 'update:modelValue': [value: boolean] }>()

const classes = computed(() => cn(
  'peer inline-flex h-6 w-10 shrink-0 cursor-pointer items-center rounded-full border border-transparent ' +
  'transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-ring ' +
  'focus-visible:ring-offset-2 focus-visible:ring-offset-background disabled:cursor-not-allowed disabled:opacity-50 ' +
  'data-[state=checked]:bg-primary data-[state=unchecked]:bg-input',
  props.class,
))
</script>

<template>
  <SwitchRoot
    :model-value="modelValue"
    :class="classes"
    @update:model-value="(v) => emit('update:modelValue', v)"
  >
    <SwitchThumb
      class="pointer-events-none block h-5 w-5 rounded-full bg-white shadow-lg ring-0 transition-transform
             data-[state=checked]:translate-x-4 data-[state=unchecked]:translate-x-0.5"
    />
  </SwitchRoot>
</template>
